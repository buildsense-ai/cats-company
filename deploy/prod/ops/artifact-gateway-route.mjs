#!/usr/bin/env node
import fs from "node:fs";
import net from "node:net";
import path from "node:path";
import process from "node:process";
import { spawnSync } from "node:child_process";
import { pathToFileURL } from "node:url";

export const ROUTE_REGISTRY_CONTRACT = "catsco.artifact-gateway-routes.v1";

const defaults = {
  registry: "/var/lib/catsco-artifact-gateway/routes.json",
  nginxRoutes: "/etc/nginx/conf.d/00-catsco-artifact-routes.conf",
  hostSuffix: "artifacts.catsco.fun",
  backendPort: 19990
};

export function registerRoute(input, options = {}) {
  const config = resolveConfig(options);
  const agentUid = normalizeAgentUid(input.agentUid);
  const privateIp = normalizePrivateIPv4(input.privateIp);
  return mutateRegistry(config, registry => {
    const previous = registry.routes[agentUid] || null;
    registry.routes[agentUid] = {
      private_ip: privateIp,
      backend_port: config.backendPort,
      updated_at: new Date().toISOString()
    };
    return {
      status: previous?.private_ip === privateIp ? "unchanged" : "registered",
      agent_uid: agentUid,
      private_ip: privateIp
    };
  });
}

export function removeRoute(input, options = {}) {
  const config = resolveConfig(options);
  const agentUid = normalizeAgentUid(input.agentUid);
  return mutateRegistry(config, registry => {
    const removed = Boolean(registry.routes[agentUid]);
    delete registry.routes[agentUid];
    return {
      status: removed ? "removed" : "not-found",
      agent_uid: agentUid
    };
  });
}

export function syncRoutes(input, options = {}) {
  const config = resolveConfig(options);
  const routes = normalizeRouteMap(input?.routes ?? input);
  return mutateRegistry(config, registry => {
    registry.routes = Object.fromEntries(Object.entries(routes).map(([agentUid, privateIp]) => [
      agentUid,
      {
        private_ip: privateIp,
        backend_port: config.backendPort,
        updated_at: new Date().toISOString()
      }
    ]));
    return { status: "synced", route_count: Object.keys(registry.routes).length };
  });
}

export function readRoute(input, options = {}) {
  const config = resolveConfig(options);
  const agentUid = normalizeAgentUid(input.agentUid);
  const registry = readRegistry(config.registry);
  const route = registry.routes[agentUid];
  return route
    ? {
        ok: true,
        status: "registered",
        agent_uid: agentUid,
        hostname: `agent-${agentUid}.${config.hostSuffix}`,
        private_ip: route.private_ip,
        backend_port: route.backend_port
      }
    : { ok: false, status: "not-found", agent_uid: agentUid };
}

export function renderNginxRoutes(registry, options = {}) {
  const config = resolveConfig(options);
  const lines = [
    "# Generated by catsco-artifact-route. Do not edit.",
    "map $host $catsco_artifact_backend {",
    "    default 127.0.0.1:1;"
  ];
  for (const [agentUid, route] of sortedRouteEntries(registry.routes)) {
    lines.push(
      `    agent-${agentUid}.${config.hostSuffix} ${route.private_ip}:${route.backend_port};`
    );
  }
  lines.push("}", "", "map $host $catsco_artifact_route_found {", "    default 0;");
  for (const [agentUid] of sortedRouteEntries(registry.routes)) {
    lines.push(`    agent-${agentUid}.${config.hostSuffix} 1;`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

function mutateRegistry(config, mutate) {
  const registry = readRegistry(config.registry);
  const result = mutate(registry);
  registry.contract_version = ROUTE_REGISTRY_CONTRACT;
  registry.updated_at = new Date().toISOString();

  fs.mkdirSync(path.dirname(config.registry), { recursive: true, mode: 0o755 });
  fs.mkdirSync(path.dirname(config.nginxRoutes), { recursive: true, mode: 0o755 });
  const previousRegistry = readOptional(config.registry);
  const previousRoutes = readOptional(config.nginxRoutes);
  const registryText = `${JSON.stringify(registry, null, 2)}\n`;
  const routesText = renderNginxRoutes(registry, config);

  atomicWrite(config.registry, registryText, 0o644);
  atomicWrite(config.nginxRoutes, routesText, 0o644);
  try {
    validateAndReload(config);
  } catch (error) {
    restoreFile(config.registry, previousRegistry, 0o644);
    restoreFile(config.nginxRoutes, previousRoutes, 0o644);
    throw error;
  }
  return {
    ok: true,
    ...result,
    route_count: Object.keys(registry.routes).length
  };
}

function validateAndReload(config) {
  if (config.skipReload) return;
  runChecked(config.nginxCommand, ["-t"], "nginx configuration validation failed");
  runChecked(config.systemctlCommand, ["reload", "nginx"], "nginx reload failed");
}

function runChecked(command, args, message) {
  const result = spawnSync(command, args, { encoding: "utf8" });
  if (result.status !== 0) {
    const detail = String(result.stderr || result.stdout || "").trim();
    throw new Error(`${message}${detail ? `: ${detail}` : ""}`);
  }
}

function resolveConfig(options = {}) {
  const env = options.env || process.env;
  const backendPort = positivePort(
    options.backendPort ?? env.CATSCO_ARTIFACT_BACKEND_PORT ?? defaults.backendPort
  );
  const skipReload = options.skipReload === true
    || (env.NODE_ENV === "test" && env.CATSCO_ARTIFACT_GATEWAY_SKIP_RELOAD === "1");
  return {
    registry: path.resolve(options.registry || env.CATSCO_ARTIFACT_ROUTE_REGISTRY || defaults.registry),
    nginxRoutes: path.resolve(options.nginxRoutes || env.CATSCO_ARTIFACT_NGINX_ROUTES || defaults.nginxRoutes),
    hostSuffix: normalizeHostname(options.hostSuffix || env.CATSCO_ARTIFACT_HOST_SUFFIX || defaults.hostSuffix),
    backendPort,
    nginxCommand: options.nginxCommand || env.CATSCO_ARTIFACT_NGINX_COMMAND || "nginx",
    systemctlCommand: options.systemctlCommand || env.CATSCO_ARTIFACT_SYSTEMCTL_COMMAND || "systemctl",
    skipReload
  };
}

function readRegistry(target) {
  if (!fs.existsSync(target)) {
    return { contract_version: ROUTE_REGISTRY_CONTRACT, routes: {} };
  }
  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(target, "utf8"));
  } catch (error) {
    throw new Error(`Artifact route registry is invalid: ${messageOf(error)}`);
  }
  if (parsed?.contract_version !== ROUTE_REGISTRY_CONTRACT || !isPlainObject(parsed.routes)) {
    throw new Error("Artifact route registry contract is invalid");
  }
  const routes = {};
  for (const [agentUid, route] of Object.entries(parsed.routes)) {
    const uid = normalizeAgentUid(agentUid);
    if (!isPlainObject(route)) throw new Error(`Artifact route ${uid} is invalid`);
    routes[uid] = {
      private_ip: normalizePrivateIPv4(route.private_ip),
      backend_port: positivePort(route.backend_port),
      updated_at: cleanText(route.updated_at)
    };
  }
  return { ...parsed, routes };
}

function normalizeRouteMap(value) {
  if (!isPlainObject(value)) throw new Error("sync input must be an object keyed by Agent UID");
  const routes = {};
  for (const [uidValue, routeValue] of Object.entries(value)) {
    const agentUid = normalizeAgentUid(uidValue);
    const privateIp = isPlainObject(routeValue)
      ? normalizePrivateIPv4(routeValue.private_ip)
      : normalizePrivateIPv4(routeValue);
    routes[agentUid] = privateIp;
  }
  return routes;
}

function normalizeAgentUid(value) {
  const text = cleanText(value);
  if (!/^[1-9]\d{0,18}$/.test(text)) throw new Error("Agent UID must be a positive integer");
  return text;
}

function normalizePrivateIPv4(value) {
  const text = cleanText(value);
  if (net.isIP(text) !== 4) throw new Error("worker private IP must be IPv4");
  const [a, b] = text.split(".").map(Number);
  const privateRange = a === 10
    || (a === 172 && b >= 16 && b <= 31)
    || (a === 192 && b === 168);
  if (!privateRange) throw new Error("worker backend must use a private IPv4 address");
  return text;
}

function normalizeHostname(value) {
  const text = cleanText(value).replace(/\.$/, "").toLowerCase();
  if (text.length > 253 || !text.includes(".") || text.split(".").some(part =>
    !/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/.test(part)
  )) throw new Error("Artifact host suffix is invalid");
  return text;
}

function positivePort(value) {
  const number = Number(value);
  if (!Number.isInteger(number) || number < 1 || number > 65535) {
    throw new Error("Artifact backend port is invalid");
  }
  return number;
}

function sortedRouteEntries(routes) {
  return Object.entries(routes).sort((left, right) => Number(left[0]) - Number(right[0]));
}

function atomicWrite(target, content, mode) {
  const temporary = `${target}.tmp-${process.pid}-${Math.random().toString(16).slice(2)}`;
  fs.writeFileSync(temporary, content, { encoding: "utf8", mode });
  fs.renameSync(temporary, target);
  fs.chmodSync(target, mode);
}

function restoreFile(target, previous, mode) {
  if (previous === null) fs.rmSync(target, { force: true });
  else atomicWrite(target, previous, mode);
}

function readOptional(target) {
  return fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
}

function isPlainObject(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function cleanText(value) {
  return String(value ?? "").trim();
}

function messageOf(error) {
  return error instanceof Error ? error.message : String(error);
}

async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString("utf8");
}

async function runCli() {
  const [command, ...args] = process.argv.slice(2);
  let result;
  if (command === "register") {
    result = registerRoute({ agentUid: args[0], privateIp: args[1] });
  } else if (command === "remove") {
    result = removeRoute({ agentUid: args[0] });
  } else if (command === "status") {
    result = readRoute({ agentUid: args[0] });
  } else if (command === "sync") {
    const input = JSON.parse(await readStdin());
    result = syncRoutes(input);
  } else if (command === "render") {
    const config = resolveConfig();
    result = { ok: true, nginx: renderNginxRoutes(readRegistry(config.registry), config) };
  } else {
    throw new Error("usage: catsco-artifact-route <register UID PRIVATE_IP|remove UID|status UID|sync|render>");
  }
  console.log(JSON.stringify(result));
  if (result.ok === false) process.exitCode = 2;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  runCli().catch(error => {
    console.error(JSON.stringify({ ok: false, error: messageOf(error) }));
    process.exit(1);
  });
}
